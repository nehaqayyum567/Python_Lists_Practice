# Make a list of 6 colors.
colors = ["red", "blue", "green", "orange", "cheery red"]
print(colors)

# Insert "Purple" at index 3.
colors.insert(3, "purple")
print(colors)

#Append "Black" at the end.
colors.append("black")
print(colors)

#Slice the middle 3 colors and print them.
middle_3 = colors[2:5]
print(middle_3)

#Reverse the list and print the final result.
colors.reverse()
print(colors)